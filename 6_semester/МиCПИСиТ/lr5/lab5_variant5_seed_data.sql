-- По одному участию на каждую из трёх конференций (первое выступление в программе — без привязки к тексту темы)
insert into "Выступление_студент" ("ID_выступления", "ID_студента")
select x."ID_выступления", s."ID_студента"
from "Студент" as s
join (
  select distinct on (k."ID_конференции")
    k."ID_конференции",
    v."ID_выступления"
  from "Конференция" as k
  join "Программа_конференции" as pc on pc."ID_конференции" = k."ID_конференции"
  join "Выступление" as v on v."ID_программы" = pc."ID_программы"
  where k."Название" in ('Информатика', 'Робототехника и ИИ', 'Энергетика и экология')
  order by k."ID_конференции", v."ID_выступления"
) as x on true
where s."ФИО" = 'Михайлова Екатерина Сергеевна'
  and not exists (
    select 1
    from "Выступление_студент" as vs
    where vs."ID_выступления" = x."ID_выступления"
      and vs."ID_студента" = s."ID_студента"
  );


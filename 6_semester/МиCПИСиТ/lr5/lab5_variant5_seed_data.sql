from "Вуз" as v
where not exists (select 1 from "Факультет" as f where f."Номер_факультета" = 4)
order by v."ID_вуза"
limit 1;

-- Группы гуманитарного сегмента (как в полном lr2)
insert into "Группа" ("ID_факультета", "Номер_группы")
select f."ID_факультета", x."Номер_группы"
from "Факультет" as f
cross join (values ('4550'), ('4551')) as x("Номер_группы")
where f."Номер_факультета" = 4
  and not exists (
    select 1
    from "Группа" as g
    where g."ID_факультета" = f."ID_факультета"
      and g."Номер_группы" = x."Номер_группы"
  );


-- AFTER INSERT: контроль максимальной численности группы + запись в журнал.
create or replace function fn_student_after_insert()
returns trigger
language plpgsql
as $$
declare
  v_cnt integer;
begin
  select count(*)
  into v_cnt
  from "Студент" s
  where s."ID_группы" = new."ID_группы";

  if v_cnt > 20 then
    raise exception 'В группе ID=% превышен лимит 20 студентов (сейчас %)', new."ID_группы", v_cnt;
  end if;

  insert into "Журнал_изменений_студент" (
    "Операция", "ID_студента", "Новое_ФИО", "Новый_ID_группы"
  )
  values (
    'AFTER INSERT', new."ID_студента", new."ФИО", new."ID_группы"
  );

  return new;
end;
$$;

create trigger trg_student_after_insert
after insert on "Студент"
for each row
execute function fn_student_after_insert();


-- AFTER UPDATE: контроль численности при переводе + запись в журнал.
create or replace function fn_student_after_update()
returns trigger
language plpgsql
as $$
declare
  v_cnt integer;
begin
  if new."ID_группы" is distinct from old."ID_группы" then
    select count(*)
    into v_cnt
    from "Студент" s
    where s."ID_группы" = new."ID_группы";

    if v_cnt > 20 then
      raise exception 'После перевода в группе ID=% превышен лимит 20 студентов (сейчас %)', new."ID_группы", v_cnt;
    end if;
  end if;

  insert into "Журнал_изменений_студент" (
    "Операция", "ID_студента", "Старое_ФИО", "Новое_ФИО", "Старый_ID_группы", "Новый_ID_группы"
  )
  values (
    'AFTER UPDATE',
    new."ID_студента",
    old."ФИО",
    new."ФИО",
    old."ID_группы",
    new."ID_группы"
  );

  return new;
end;
$$;

create trigger trg_student_after_update
after update on "Студент"
for each row
execute function fn_student_after_update();


-- AFTER DELETE: удаление пустой группы + запись в журнал.
create or replace function fn_student_after_delete()
returns trigger
language plpgsql
as $$
begin
  if not exists (
    select 1
    from "Студент" s
    where s."ID_группы" = old."ID_группы"
  ) then
    delete from "Группа" g
    where g."ID_группы" = old."ID_группы";
  end if;

  insert into "Журнал_изменений_студент" (
    "Операция", "ID_студента", "Старое_ФИО", "Старый_ID_группы"
  )
  values (
    'AFTER DELETE', old."ID_студента", old."ФИО", old."ID_группы"
  );

  return old;
end;
$$;

create trigger trg_student_after_delete
after delete on "Студент"
for each row
execute function fn_student_after_delete();



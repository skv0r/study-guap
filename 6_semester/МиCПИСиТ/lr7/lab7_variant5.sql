create or replace view v_student_editor as
select
  s."ID_студента",
  s."ФИО",
  g."Номер_группы",
  f."Номер_факультета",
  vz."Название" as "Вуз"
from "Студент" s
join "Группа" g on g."ID_группы" = s."ID_группы"
join "Факультет" f on f."ID_факультета" = g."ID_факультета"
join "Вуз" vz on vz."ID_вуза" = f."ID_вуза";


create or replace function fn_v_student_editor_ins()
returns trigger
language plpgsql
as $$
declare
  v_id_fakulteta integer;
  v_id_grupy integer;
begin
  select f."ID_факультета"
  into v_id_fakulteta
  from "Факультет" f
  join "Вуз" vz on vz."ID_вуза" = f."ID_вуза"
  where f."Номер_факультета" = new."Номер_факультета"
    and vz."Название" = new."Вуз";

  if v_id_fakulteta is null then
    raise exception 'Не найден факультет №% в вузе %', new."Номер_факультета", new."Вуз";
  end if;

  select g."ID_группы"
  into v_id_grupy
  from "Группа" g
  where g."ID_факультета" = v_id_fakulteta
    and g."Номер_группы" = new."Номер_группы";

  if v_id_grupy is null then
    insert into "Группа" ("ID_факультета", "Номер_группы")
    values (v_id_fakulteta, new."Номер_группы")
    returning "ID_группы" into v_id_grupy;
  end if;

  insert into "Студент" ("ID_группы", "ФИО")
  values (v_id_grupy, new."ФИО")
  returning "ID_студента" into new."ID_студента";

  return new;
end;
$$;

create trigger trg_v_student_editor_ins
instead of insert on v_student_editor
for each row
execute function fn_v_student_editor_ins();


create or replace function fn_v_student_editor_upd()
returns trigger
language plpgsql
as $$
declare
  v_id_fakulteta integer;
  v_id_grupy integer;
begin
  select f."ID_факультета"
  into v_id_fakulteta
  from "Факультет" f
  join "Вуз" vz on vz."ID_вуза" = f."ID_вуза"
  where f."Номер_факультета" = new."Номер_факультета"
    and vz."Название" = new."Вуз";

  if v_id_fakulteta is null then
    raise exception 'Не найден факультет №% в вузе %', new."Номер_факультета", new."Вуз";
  end if;

  select g."ID_группы"
  into v_id_grupy
  from "Группа" g
  where g."ID_факультета" = v_id_fakulteta
    and g."Номер_группы" = new."Номер_группы";

  if v_id_grupy is null then
    insert into "Группа" ("ID_факультета", "Номер_группы")
    values (v_id_fakulteta, new."Номер_группы")
    returning "ID_группы" into v_id_grupy;
  end if;

  update "Студент"
  set
    "ФИО" = new."ФИО",
    "ID_группы" = v_id_grupy
  where "ID_студента" = old."ID_студента";

  return new;
end;
$$;

create trigger trg_v_student_editor_upd
instead of update on v_student_editor
for each row
execute function fn_v_student_editor_upd();


create or replace function fn_v_student_editor_del()
returns trigger
language plpgsql
as $$
begin
  delete from "Студент"
  where "ID_студента" = old."ID_студента";

  return old;
end;
$$;

create trigger trg_v_student_editor_del
instead of delete on v_student_editor
for each row
execute function fn_v_student_editor_del();


-- ============================================================
-- 3) AFTER-триггер статистики (insert/update/delete)
-- ============================================================

create or replace function fn_vs_stats_after_ins_upd_del()
returns trigger
language plpgsql
as $$
declare
  v_id_conf_old integer;
  v_id_conf_new integer;
begin
  if tg_op in ('DELETE', 'UPDATE') then
    select pc."ID_конференции"
    into v_id_conf_old
    from "Выступление" v
    join "Программа_конференции" pc on pc."ID_программы" = v."ID_программы"
    where v."ID_выступления" = old."ID_выступления";

    if v_id_conf_old is not null then
      insert into "Статистика_участий_по_конференции" (
        "ID_конференции", "Название_конференции", "Количество_участий", "Дата_обновления"
      )
      select
        k."ID_конференции", k."Название", 0, now()
      from "Конференция" k
      where k."ID_конференции" = v_id_conf_old
      on conflict ("ID_конференции") do nothing;

      update "Статистика_участий_по_конференции"
      set
        "Количество_участий" = greatest(0, "Количество_участий" - 1),
        "Дата_обновления" = now()
      where "ID_конференции" = v_id_conf_old;
    end if;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    select pc."ID_конференции"
    into v_id_conf_new
    from "Выступление" v
    join "Программа_конференции" pc on pc."ID_программы" = v."ID_программы"
    where v."ID_выступления" = new."ID_выступления";

    if v_id_conf_new is not null then
      insert into "Статистика_участий_по_конференции" (
        "ID_конференции", "Название_конференции", "Количество_участий", "Дата_обновления"
      )
      select
        k."ID_конференции", k."Название", 0, now()
      from "Конференция" k
      where k."ID_конференции" = v_id_conf_new
      on conflict ("ID_конференции") do nothing;

      update "Статистика_участий_по_конференции"
      set
        "Количество_участий" = "Количество_участий" + 1,
        "Дата_обновления" = now()
      where "ID_конференции" = v_id_conf_new;
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

create trigger trg_vs_stats_after_ins_upd_del
after insert or update or delete on "Выступление_студент"
for each row
execute function fn_vs_stats_after_ins_upd_del();


-- Инициализация статистики по текущим данным.
insert into "Статистика_участий_по_конференции" (
  "ID_конференции", "Название_конференции", "Количество_участий", "Дата_обновления"
)
select
  k."ID_конференции",
  k."Название",
  count(vs."ID_студента")::integer as "Количество_участий",
  now()
from "Конференция" k
left join "Программа_конференции" pc on pc."ID_конференции" = k."ID_конференции"
left join "Выступление" v on v."ID_программы" = pc."ID_программы"
left join "Выступление_студент" vs on vs."ID_выступления" = v."ID_выступления"
group by k."ID_конференции", k."Название"
on conflict ("ID_конференции") do update
set
  "Название_конференции" = excluded."Название_конференции",
  "Количество_участий" = excluded."Количество_участий",
  "Дата_обновления" = now();



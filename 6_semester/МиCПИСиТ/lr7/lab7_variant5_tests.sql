-- ============================================================
-- ПУНКТ 1 / РИСУНОК 1
-- INSTEAD OF INSERT через представление v_student_editor
-- ============================================================

delete from "Студент"
where "ФИО" = 'Тест ЛР7 Представление INSERT';

insert into v_student_editor ("ФИО", "Номер_группы", "Номер_факультета", "Вуз")
values ('Тест ЛР7 Представление INSERT', '4999', 4, 'ГУАП');

select
  s."ID_студента",
  s."ФИО",
  g."Номер_группы",
  f."Номер_факультета",
  vz."Название" as "Вуз"
from "Студент" s
join "Группа" g on g."ID_группы" = s."ID_группы"
join "Факультет" f on f."ID_факультета" = g."ID_факультета"
join "Вуз" vz on vz."ID_вуза" = f."ID_вуза"
where s."ФИО" = 'Тест ЛР7 Представление INSERT';


-- ============================================================
-- ПУНКТ 2 / РИСУНОК 2
-- INSTEAD OF UPDATE через представление v_student_editor
-- ============================================================

update v_student_editor
set "Номер_группы" = '4550'
where "ФИО" = 'Тест ЛР7 Представление INSERT';

select
  s."ФИО",
  g."Номер_группы",
  f."Номер_факультета"
from "Студент" s
join "Группа" g on g."ID_группы" = s."ID_группы"
join "Факультет" f on f."ID_факультета" = g."ID_факультета"
where s."ФИО" = 'Тест ЛР7 Представление INSERT';


-- ============================================================
-- ПУНКТ 3 / РИСУНОК 3
-- INSTEAD OF DELETE через представление v_student_editor
-- ============================================================

select
  'До удаления' as "Этап",
  v."ID_студента",
  v."ФИО",
  v."Номер_группы",
  v."Номер_факультета",
  v."Вуз"
from v_student_editor v
where v."ФИО" = 'Тест ЛР7 Представление INSERT';

delete from v_student_editor
where "ФИО" = 'Тест ЛР7 Представление INSERT';

select
  'После удаления' as "Этап",
  case
    when exists (
      select 1
      from v_student_editor v
      where v."ФИО" = 'Тест ЛР7 Представление INSERT'
    ) then 'Запись осталась'
    else 'Запись удалена'
  end as "Статус";



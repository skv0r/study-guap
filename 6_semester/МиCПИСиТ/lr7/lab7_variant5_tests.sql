-- ============================================================
-- ПУНКТ 8 / РИСУНОК 8
-- Статистика участий по конференциям
-- ============================================================

with base_student as (
  select s."ID_студента"
  from "Студент" s
  where s."ФИО" = 'Алексеев Иван Сергеевич'
  limit 1
),
target_speech as (
  select v."ID_выступления"
  from "Выступление" v
  join "Программа_конференции" pc on pc."ID_программы" = v."ID_программы"
  join "Конференция" k on k."ID_конференции" = pc."ID_конференции"
  where k."Название" = 'Энергетика и экология'
  order by v."ID_выступления"
  limit 1
)
insert into "Выступление_студент" ("ID_выступления", "ID_студента")
select ts."ID_выступления", bs."ID_студента"
from target_speech ts
cross join base_student bs
on conflict do nothing;

select *
from "Статистика_участий_по_конференции"
order by "ID_конференции";

-- г) Среднее число участников одного выступления на конференции «Информатика»
--     (по каждому выступлению считается число строк в «Выступление_студент», затем берётся среднее)

select avg(t."Участников_на_выступление")
from (
  select
    count("Выступление_студент"."ID_студента")::numeric as "Участников_на_выступление"
  from "Выступление"
  join "Программа_конференции"
    on "Программа_конференции"."ID_программы" = "Выступление"."ID_программы"
  join "Конференция"
    on "Конференция"."ID_конференции" = "Программа_конференции"."ID_конференции"
  join "Выступление_студент"
    on "Выступление_студент"."ID_выступления" = "Выступление"."ID_выступления"
  where "Конференция"."Название" = 'Информатика'
  group by "Выступление"."ID_выступления"
) as t;


-- д) Конференции, в программе которых наибольшее число выступлений

with "Число_выступлений" as (
  select
    "Конференция"."Название" as "Конференция",
    count("Выступление"."ID_выступления") as "Выступлений"
  from "Конференция"
  join "Программа_конференции"
    on "Программа_конференции"."ID_конференции" = "Конференция"."ID_конференции"
  join "Выступление"
    on "Выступление"."ID_программы" = "Программа_конференции"."ID_программы"
  group by "Конференция"."Название"
)
select
  cw."Конференция",
  cw."Выступлений"
from "Число_выступлений" as cw
where cw."Выступлений" = (select max(cw2."Выступлений") from "Число_выступлений" as cw2);


-- е) Номера факультетов, для которых минимально суммарное число участий студентов в выступлениях
--     (учитываются все строки «Выступление_студент» студентов групп этого факультета; нули — через подзапрос)

with "Участия_по_факультету" as (
  select
    "Факультет"."Номер_факультета" as "Номер_факультета",
    (
      select count(*)
      from "Выступление_студент" as vs
      join "Студент" as st on st."ID_студента" = vs."ID_студента"
      join "Группа" as gp on gp."ID_группы" = st."ID_группы"
      where gp."ID_факультета" = "Факультет"."ID_факультета"
    ) as "Участий"
  from "Факультет"
  join "Вуз" on "Вуз"."ID_вуза" = "Факультет"."ID_вуза"
  where "Вуз"."Название" = 'ГУАП'
)
select
  upf."Номер_факультета",
  upf."Участий"
from "Участия_по_факультету" as upf
where upf."Участий" = (select min(upf2."Участий") from "Участия_по_факультету" as upf2);


-- демонстрация основных агрегатных функций
-- сводка по конференциям: число выступлений, участий, min / max / avg / sum по длине темы

with "Выступление_сводка" as (
  select
    "Конференция"."Название" as "Конференция",
    "Выступление"."ID_выступления",
    length("Выступление"."Название_темы") as "Длина_темы",
    (
      select count(*)
      from "Выступление_студент" as vs
      where vs."ID_выступления" = "Выступление"."ID_выступления"
    ) as "Участников"
  from "Конференция"
  join "Программа_конференции"
    on "Программа_конференции"."ID_конференции" = "Конференция"."ID_конференции"
  join "Выступление"
    on "Выступление"."ID_программы" = "Программа_конференции"."ID_программы"
)
select
  "Конференция",
  count(*) as "Выступлений",
  sum("Участников") as "Назначений_участников",
  min("Длина_темы") as "Мин_длина_темы",
  max("Длина_темы") as "Макс_длина_темы",
  avg("Длина_темы")::numeric(10, 2) as "Средняя_длина_темы",
  sum("Длина_темы") as "Сумма_длин_названий_тем"
from "Выступление_сводка"
group by "Конференция"
order by "Выступлений" desc, "Конференция";


-- демонстрация HAVING: конференции, где выступлений больше двух

select
  "Конференция"."Название" as "Конференция",
  count(distinct "Выступление"."ID_выступления") as "Выступлений"
from "Конференция"
join "Программа_конференции"
  on "Программа_конференции"."ID_конференции" = "Конференция"."ID_конференции"
join "Выступление"
  on "Выступление"."ID_программы" = "Программа_конференции"."ID_программы"
group by "Конференция"."Название"
having count(distinct "Выступление"."ID_выступления") > 2
order by "Выступлений" desc;


-- теоретико-множественные операции и мультимножества
-- множество A: ФИО студентов, выступавших на конференции «Информатика»
-- множество B: ФИО студентов, выступавших на конференции «Робототехника и ИИ»

with "A" as (
  select distinct "Студент"."ФИО"
  from "Студент"
  join "Выступление_студент" on "Выступление_студент"."ID_студента" = "Студент"."ID_студента"
  join "Выступление" on "Выступление"."ID_выступления" = "Выступление_студент"."ID_выступления"
  join "Программа_конференции" on "Программа_конференции"."ID_программы" = "Выступление"."ID_программы"
  join "Конференция" on "Конференция"."ID_конференции" = "Программа_конференции"."ID_конференции"
  where "Конференция"."Название" = 'Информатика'
),
"B" as (
  select distinct "Студент"."ФИО"
  from "Студент"
  join "Выступление_студент" on "Выступление_студент"."ID_студента" = "Студент"."ID_студента"
  join "Выступление" on "Выступление"."ID_выступления" = "Выступление_студент"."ID_выступления"
  join "Программа_конференции" on "Программа_конференции"."ID_программы" = "Выступление"."ID_программы"
  join "Конференция" on "Конференция"."ID_конференции" = "Программа_конференции"."ID_конференции"
  where "Конференция"."Название" = 'Робототехника и ИИ'
)
select "ФИО", count(*) as "Кратность_в_результате"
from (
  select * from "A"

  intersect all

  select * from "B"
) as t
group by "ФИО";

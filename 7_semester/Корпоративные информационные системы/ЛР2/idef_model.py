def b(title, child=None, num=None):
    box = {"title": title, "child": child}
    if num is not None:
        box["num"] = num
    return box


def arr(label, to=None, frm=None):
    item = {"label": label}
    if to is not None:
        item["to"] = to if isinstance(to, list) else [to]
    if frm is not None:
        item["frm"] = frm
    return item


def flow(label, frm, to):
    return {"label": label, "frm": frm, "to": to}



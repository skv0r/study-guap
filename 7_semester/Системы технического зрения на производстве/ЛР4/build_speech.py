def rfonts(run, name):
    run.font.name = name
    run.font.color.rgb = BLACK
    rpr = run._element.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.append(fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(attr), name)


def style_run(run, size=14, bold=False):
    rfonts(run, "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = False


def set_spacing(paragraph, before=0, after=0, line=360):
    fmt = paragraph.paragraph_format
    fmt.space_before = Pt(before)
    fmt.space_after = Pt(after)
    fmt.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    paragraph.paragraph_format.line_spacing = line / 240.0


def set_indent(paragraph, first=0):
    ppr = paragraph._p.get_or_add_pPr()
    ind = ppr.find(qn("w:ind"))
    if ind is None:
        ind = OxmlElement("w:ind")
        ppr.append(ind)
    ind.set(qn("w:firstLine"), str(first))


def add_paragraph(doc, text, *, center=False, bold=False, first=709, before=0, after=0, size=14):
    paragraph = doc.add_paragraph()
    set_spacing(paragraph, before, after)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    if not center:
        set_indent(paragraph, first)
    run = paragraph.add_run(text)
    style_run(run, size=size, bold=bold)
    return paragraph


def margins(section):
    section.top_margin = Twips(1134)
    section.bottom_margin = Twips(1134)
    section.left_margin = Twips(1701)
    section.right_margin = Twips(850)


def write_docx():
    doc = Document()
    margins(doc.sections[0])
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(14)
    normal.font.color.rgb = BLACK
    add_paragraph(doc, "Текст доклада", center=True, bold=True, before=0, after=6)
    add_paragraph(
        doc,
        "Детекторы признаков на изображении детали. Лабораторная работа 4",
        center=True,
        before=0,
        after=12,
    )
    for title, paragraphs in SLIDES:
        add_paragraph(doc, title, bold=True, first=709, before=12, after=6)
        for text in paragraphs:
            add_paragraph(doc, text)
    doc.save(str(OUT))


def write_notes():
    prs = Presentation(str(PPTX))
    if len(prs.slides) != len(SLIDES):
        raise SystemExit(f"Слайдов {len(prs.slides)}, текстов {len(SLIDES)}")
    for slide, (_, paragraphs) in zip(prs.slides, SLIDES):
        slide.notes_slide.notes_text_frame.text = "\n\n".join(paragraphs)
    prs.save(str(PPTX))


if __name__ == "__main__":
    write_docx()

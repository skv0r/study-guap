-- 2. Неповторяемое чтение ==========

-- --- сеанс A ---
COMMIT;
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
SELECT "Название_темы"
FROM "Выступление"
WHERE "Название_темы" = 'Черновик темы для проверки изоляции'
   OR "Название_темы" = 'Черновик темы после фиксации правки';

-- --- сеанс B ---
COMMIT;
BEGIN;
UPDATE "Выступление"
SET "Название_темы" = 'Черновик темы после фиксации правки'
WHERE "Название_темы" = 'Черновик темы для проверки изоляции';
COMMIT;

-- --- сеанс A, второе чтение ---
SELECT "Название_темы"
FROM "Выступление"
WHERE "Название_темы" = 'Черновик темы после фиксации правки'
   OR "Название_темы" = 'Черновик темы для проверки изоляции';
ROLLBACK;

-- Повтор на снимке: в сеансе A вместо READ COMMITTED —

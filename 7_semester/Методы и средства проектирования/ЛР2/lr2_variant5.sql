);
-- ожидается исходная тема «Черновик…», не «НЕЗАФИКСИРОВАННАЯ…»

-- --- сеанс A ---
ROLLBACK;

-- --- сеанс B ---
SELECT "ID_выступления", "Название_темы"
FROM "Выступление"
WHERE "Название_темы" = 'Черновик темы для проверки изоляции';

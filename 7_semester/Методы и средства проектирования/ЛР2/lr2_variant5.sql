-- ========== 1. Грязное чтение ==========
-- READ UNCOMMITTED = READ COMMITTED, чужую незафиксированную правку не видно.

COMMIT;
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
UPDATE "Выступление"
SET "Название_темы" = 'НЕЗАФИКСИРОВАННАЯ ПРАВКА ТЕМЫ'
WHERE "Название_темы" = 'Черновик темы для проверки изоляции'
   OR "Название_темы" = 'НЕЗАФИКСИРОВАННАЯ ПРАВКА ТЕМЫ';
SELECT "ID_выступления", "Название_темы"
FROM "Выступление"
WHERE "Название_темы" IN (
  'НЕЗАФИКСИРОВАННАЯ ПРАВКА ТЕМЫ',
  'Черновик темы для проверки изоляции'
);

-- --- сеанс B (второе соединение), пока A не завершил транзакцию ---
COMMIT;
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
SHOW transaction_isolation;
SELECT "ID_выступления", "Название_темы"
FROM "Выступление"
WHERE "Название_темы" IN (
  'НЕЗАФИКСИРОВАННАЯ ПРАВКА ТЕМЫ',

-- ========== 4. Блокировки ==========
-- Подставьте ID Соколова из подготовки (ниже — 100009, если совпал).

-- --- сеанс-держатель (application_name удобно задать в клиенте) ---
COMMIT;
BEGIN;
UPDATE "Студент"
SET "ФИО" = "ФИО"
WHERE "ФИО" = 'Соколов Игорь Павлович';
-- транзакцию не закрывать

-- --- сеанс-ожидающий (второе соединение) ---
COMMIT;
BEGIN;
SELECT "ФИО"
FROM "Студент"
WHERE "ФИО" = 'Соколов Игорь Павлович'
FOR SHARE;
-- запрос ждёт

-- --- третье соединение: отчёт о блокировках ---
SELECT l.pid,
       c.application_name,
       l.locktype,
       l.mode,
       l.granted,
       CASE WHEN l.relation IS NULL THEN NULL ELSE l.relation::regclass::text END AS relation,
       c.wait_event_type,
       c.wait_event,
       left(c.query, 180) AS query
FROM pg_locks l
JOIN pg_stat_activity c ON c.pid = l.pid
WHERE c.query ILIKE '%Соколов%'
   OR c.query ILIKE '%FOR SHARE%'
   OR c.application_name IN ('lock_holder', 'lock_waiter')
ORDER BY l.pid, l.granted DESC, l.locktype, l.mode;


# -*- coding: utf-8 -*-
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from docx_common import (
    add_caption, add_code, add_contents_title, add_figure, add_h, add_p, add_table, add_toc_item,
    measure_pages, new_doc,
)

BASE = Path(__file__).resolve().parent
FIG = BASE / "ЛР4" / "figures"
OUT = BASE / "ЛР4" / "ЛР4_Отчет_Буренков_МиСП.docx"
TOC = ["1 Цель работы", "2 Задание", "3 Ход работы", "4 Выводы"]


def build(pages):
    doc = new_doc("4", "Репликация слиянием, фрагмент и конфликт")
    add_contents_title(doc)
    for title in TOC:
        add_toc_item(doc, title, pages[title])

    add_h(doc, "1 Цель работы", page_break=True)
    add_p(
        doc,
        "Получить навык фрагментации таблицы «Студент» по факультету в PostgreSQL "
        "и разбора конфликта по одной и той же конференции, изменённой в центре и на узле.",
    )

    add_h(doc, "2 Задание", page_break=True)
    add_p(
        doc,
        "Разделить данные варианта 5 так, чтобы на узел факультета попадали только его студенты. "
        "Смоделировать конфликт двух правок одной строки и показать, как сервер его объявляет и как правка выравнивается. "
        "Запросы выполняются отдельными блоками.",
    )

    add_h(doc, "3 Ход работы", page_break=True)
    add_p(
        doc,
        "Среда работы — PostgreSQL. Центр находится в схеме office, узел факультета 4 — в схеме node4. "
        "На узел копируется только студент факультета 4. Конференция 7 сначала одинакова на обеих сторонах, "
        "затем названия расходятся. Сверка поднимает исключение, пока тексты разные, и проходит, "
        "когда на узле оставлено название центра.",
    )

    add_h(doc, "3.1 Фрагмент факультета 4")
    add_p(doc, "Отбор фрагмента сидит в триггере вставки:")
    add_code(doc, 'IF NEW."Факультет" = 4 THEN')
    add_code(doc, '    INSERT INTO node4."Студент" ("ID", "ФИО", "Факультет")')
    add_code(doc, '    VALUES (NEW."ID", NEW."ФИО", NEW."Факультет");')
    add_code(doc, "END IF;")
    add_p(
        doc,
        "Иванов Иван относится к факультету 1, Сидорова Анна — к факультету 4. "
        "На рисунке 1 в центре две строки. На рисунке 2 на узле одна: только факультет 4. "
        "Сводка приведена в таблице 1.",
    )
    add_figure(doc, FIG / "center.png", "Рисунок 1 — студенты в центре")
    add_figure(doc, FIG / "node.png", "Рисунок 2 — фрагмент узла факультета 4")
    add_caption(doc, "Таблица 1 — Фрагмент по факультету 4")
    add_table(
        doc,
        ["Сторона", "ID", "ФИО", "Факультет", "На узле"],
        [
            ["центр", "1", "Иванов Иван", "1", "нет"],
            ["центр и узел", "2", "Сидорова Анна", "4", "да"],
        ],
        [3.5, 1.5, 4.5, 3, 4],
    )

    add_h(doc, "3.2 Конфликт")
    add_p(
        doc,
        "Конференция 7 сначала называлась «Цифровой вуз» на обеих сторонах. "
        "Затем центр записал «Цифровой вуз, пленарное», а узел — «Цифровой вуз, секция». "
        "На рисунке 3 эти два текста видны в одной выборке. Названия до разрешения сведены в таблице 2. "
        "Сверка на рисунке 4 оператор не выполняет. Ответ сервера:",
    )
    add_code(doc, "ERROR:  конфликт репликации: центр [Цифровой вуз, пленарное], узел [Цифровой вуз, секция]")
    add_code(doc, "КОНТЕКСТ:  PL/pgSQL function office.check_conflict() line 7 at RAISE")
    add_figure(doc, FIG / "conflict.png", "Рисунок 3 — конференция 7 до разрешения конфликта")
    add_caption(doc, "Таблица 2 — Строка конференции до разрешения")
    add_table(
        doc,
        ["Сторона", "ID", "Название"],
        [["центр", "7", "Цифровой вуз, пленарное"], ["узел факультета 4", "7", "Цифровой вуз, секция"]],
        [5, 2, 9.5],
    )
    add_figure(doc, FIG / "error.png", "Рисунок 4 — отказ сверки при двух названиях")

    add_h(doc, "3.3 Разрешение конфликта")
    add_p(
        doc,
        "Разрешение оставляет значение центра. Узел получает «Цифровой вуз, пленарное». "
        "Повторная сверка проходит без ошибки. На рисунке 5 обе стороны возвращают одно название.",
    )
    add_figure(doc, FIG / "fixed.png", "Рисунок 5 — конференция 7 после выравнивания")

    add_h(doc, "4 Выводы", page_break=True)
    add_p(
        doc,
        "Фрагмент узла ограничен факультетом 4: в выборке центра две строки, на узле только Сидорова Анна. "
        "Иванов Иван, факультет 1, на узел не попал. "
        "Конфликт конференции 7 сервер объявил текстом «конфликт репликации: центр [Цифровой вуз, пленарное], узел [Цифровой вуз, секция]». "
        "После выравнивания обе стороны вернули «Цифровой вуз, пленарное».",
    )
    doc.save(OUT)


def main():
    build({title: "…" for title in TOC})
    pages = measure_pages(OUT, TOC)
    build(pages)
    print(pages)


if __name__ == "__main__":
    main()

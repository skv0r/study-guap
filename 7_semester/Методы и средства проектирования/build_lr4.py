# -*- coding: utf-8 -*-
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from docx_common import (
    add_caption, add_code, add_contents_title, add_figure, add_h, add_p, add_table, add_toc_item,
    measure_pages, new_doc,
)

BASE = Path(__file__).resolve().parent
FIG = BASE / "ЛР4" / "figures"
OUT = BASE / "ЛР4" / "ЛР4_Отчет_Буренков_МиСП.docx"
TOC = ["1 Цель работы", "2 Задание", "3 Ход работы", "4 Выводы"]


def build(pages):
    doc = new_doc("4", "Репликация слиянием, фрагмент и конфликт")
    add_contents_title(doc)
    for title in TOC:
        add_toc_item(doc, title, pages[title])

    add_h(doc, "1 Цель работы", page_break=True)
    add_p(
        doc,
        "Освоить репликацию слиянием на данных вуза: отдать узлу факультета только его фрагмент "
        "и разобрать конфликт, который появляется, когда одну и ту же строку меняют в центре и на узле до сверки.",
    )

    add_h(doc, "2 Задание", page_break=True)
    add_p(
        doc,
        "Реализовать в базе репликацию слиянием и фрагментацию, которая соответствует задаче предметной области. "
        "Смоделировать конфликт репликации и устранить его. Предметная область — автоматизированная информационная "
        "система университета. Среда работы — PostgreSQL. Центр и узел факультета 4 находятся в одной базе, "
        "в схемах office и node4. Запросы выполняются отдельными блоками: объекты, затем вставки, затем конфликт, "
        "затем разрешение.",
    )
    add_p(doc, "По заданию в отчёте нужны три результата.")
    add_p(
        doc,
        "Первый — объекты репликации. Издатель хранит полные статьи. Подписчик получает свою часть. "
        "Для статьи «Студент» задаётся горизонтальный фрагмент: на узел попадает только факультет 4. "
        "Статья «Конференция» общая, её строка может меняться с обеих сторон.",
    )
    add_p(
        doc,
        "Второй — операторы, которыми данные вставляются и изменяются при проверке, и содержимое таблиц после них. "
        "По студентам должно быть видно, что чужой факультет на узел не попал. По конференции должно быть видно "
        "исходное общее название и два разных названия после правок.",
    )
    add_p(
        doc,
        "Третий — описание моделирования и устранения конфликта. Конфликт получается, когда конференция 7 "
        "после общего исходного названия изменена в центре и на узле по-разному. Сверка должна объявить оба текста. "
        "Устранение оставляет значение издателя, после чего обе стороны возвращают одно название.",
    )

    add_h(doc, "3 Ход работы", page_break=True)
    add_p(
        doc,
        "Репликация слиянием передаёт изменения между базами, которые работают отдельно и сверяются, когда появляется связь. "
        "В этой работе издатель — схема office. Подписчик — схема node4, узел факультета 4. "
        "Публикация состоит из двух статей. «Студент» идёт из центра на узел и только строками факультета 4: "
        "узлу факультета не нужен список чужих студентов. «Конференция» есть на обеих сторонах и меняется в обе стороны: "
        "название может поправить и центр, и факультет. Пока сверки нет, каждая сторона хранит свой текст. "
        "Сверка сравнивает одну и ту же строку. Разные тексты — конфликт. Разрешение записывает на узел значение центра.",
    )
    add_caption(doc, "Таблица 1 — Объекты репликации")
    add_table(
        doc,
        ["Роль", "Объект", "Назначение"],
        [
            ["издатель", "схема office", "полные статьи «Студент» и «Конференция»"],
            ["подписчик", "схема node4", "фрагмент факультета 4 и своя копия конференции"],
            ["статья", "Студент", "горизонтальный фрагмент, факультет равен 4"],
            ["статья", "Конференция", "общая строка, правки с обеих сторон"],
            ["фильтр", "триггер frag", "копирует вставку студента только для факультета 4"],
            ["сверка", "office.check_conflict", "сравнивает названия конференции 7"],
        ],
        [3.2, 4.3, 9],
    )

    add_h(doc, "3.1 Объекты репликации")
    add_p(
        doc,
        "Сначала создаются схема издателя, схема подписчика и одинаковые таблицы статей. "
        "Одинаковая структура нужна, чтобы строка центра могла лечь в таблицу узла.",
    )
    add_code(
        doc,
        "CREATE SCHEMA office;\n"
        "CREATE SCHEMA node4;\n"
        "\n"
        "CREATE TABLE office.\"Студент\" (\n"
        "  \"ID\" integer PRIMARY KEY,\n"
        "  \"ФИО\" varchar(100) NOT NULL,\n"
        "  \"Факультет\" smallint NOT NULL\n"
        ");\n"
        "CREATE TABLE node4.\"Студент\" (\n"
        "  LIKE office.\"Студент\" INCLUDING ALL\n"
        ");\n"
        "\n"
        "CREATE TABLE office.\"Конференция\" (\n"
        "  \"ID\" integer PRIMARY KEY,\n"
        "  \"Название\" varchar(150) NOT NULL\n"
        ");\n"
        "CREATE TABLE node4.\"Конференция\" (\n"
        "  LIKE office.\"Конференция\" INCLUDING ALL\n"
        ");",
    )
    add_p(
        doc,
        "Фрагмент студентов задаёт триггер после вставки в таблицу издателя. "
        "Условие факультета — это и есть отбор строк под задачу узла. Строка с другим факультетом в центре остаётся, "
        "в node4.\"Студент\" она не записывается.",
    )
    add_code(
        doc,
        "CREATE OR REPLACE FUNCTION office.copy_student()\n"
        "RETURNS trigger\n"
        "LANGUAGE plpgsql\n"
        "AS $$\n"
        "BEGIN\n"
        "  IF NEW.\"Факультет\" = 4 THEN\n"
        "    INSERT INTO node4.\"Студент\" (\"ID\", \"ФИО\", \"Факультет\")\n"
        "    VALUES (NEW.\"ID\", NEW.\"ФИО\", NEW.\"Факультет\");\n"
        "  END IF;\n"
        "  RETURN NEW;\n"
        "END;\n"
        "$$;\n"
        "\n"
        "CREATE TRIGGER frag\n"
        "AFTER INSERT ON office.\"Студент\"\n"
        "FOR EACH ROW EXECUTE FUNCTION office.copy_student();",
    )

    add_h(doc, "3.2 Операторы модификации и содержимое таблиц")
    add_p(
        doc,
        "Проверка фрагмента — две вставки в центр. Первая относится к факультету 1, вторая — к факультету 4.",
    )
    add_code(
        doc,
        "INSERT INTO office.\"Студент\" (\"ID\", \"ФИО\", \"Факультет\")\n"
        "VALUES (1, 'Иванов Иван', 1);\n"
        "\n"
        "INSERT INTO office.\"Студент\" (\"ID\", \"ФИО\", \"Факультет\")\n"
        "VALUES (2, 'Сидорова Анна', 4);",
    )
    add_p(doc, "Содержимое после вставок читается отдельно на издателе и на подписчике.")
    add_code(
        doc,
        "SELECT \"ID\", \"ФИО\", \"Факультет\"\n"
        "FROM office.\"Студент\" ORDER BY \"ID\";\n"
        "\n"
        "SELECT \"ID\", \"ФИО\", \"Факультет\"\n"
        "FROM node4.\"Студент\" ORDER BY \"ID\";",
    )
    add_p(
        doc,
        "Издатель вернул две строки. Подписчик вернул одну. Иванов Иван, факультет 1, на узел не попал. "
        "Сидорова Анна, факультет 4, есть на обеих сторонах. На рисунке 1 виден центр, на рисунке 2 — узел. "
        "Те же строки сведены в таблице 2.",
    )
    add_figure(doc, FIG / "center.png", "Рисунок 1 — Студенты издателя после двух вставок")
    add_figure(doc, FIG / "node.png", "Рисунок 2 — Фрагмент подписчика, факультет 4")
    add_caption(doc, "Таблица 2 — Содержимое статьи «Студент»")
    add_table(
        doc,
        ["Сторона", "ID", "ФИО", "Факультет"],
        [
            ["издатель", "1", "Иванов Иван", "1"],
            ["издатель", "2", "Сидорова Анна", "4"],
            ["подписчик", "2", "Сидорова Анна", "4"],
        ],
        [4, 2, 6, 4.5],
    )

    add_h(doc, "3.3 Моделирование конфликта")
    add_p(
        doc,
        "Конфликт слияния появляется, когда одну запись меняют на разных сторонах до сверки. "
        "Для этого конференция 7 сначала создаётся с одним названием и у издателя, и у подписчика. "
        "Это общее состояние до расхождения.",
    )
    add_code(
        doc,
        "INSERT INTO office.\"Конференция\" (\"ID\", \"Название\")\n"
        "VALUES (7, 'Цифровой вуз');\n"
        "\n"
        "INSERT INTO node4.\"Конференция\" (\"ID\", \"Название\")\n"
        "VALUES (7, 'Цифровой вуз');",
    )
    add_p(
        doc,
        "Затем каждая сторона записывает своё уточнение. Центр помечает пленарное заседание, "
        "узел — секцию. Связи между правками нет: второй оператор не читает результат первого.",
    )
    add_code(
        doc,
        "UPDATE office.\"Конференция\"\n"
        "SET \"Название\" = 'Цифровой вуз, пленарное'\n"
        "WHERE \"ID\" = 7;\n"
        "\n"
        "UPDATE node4.\"Конференция\"\n"
        "SET \"Название\" = 'Цифровой вуз, секция'\n"
        "WHERE \"ID\" = 7;",
    )
    add_p(doc, "Выборка одной строки с обеих сторон показывает два текста.")
    add_code(
        doc,
        "SELECT 'центр' AS сторона, \"Название\"\n"
        "FROM office.\"Конференция\" WHERE \"ID\" = 7\n"
        "UNION ALL\n"
        "SELECT 'узел_4', \"Название\"\n"
        "FROM node4.\"Конференция\" WHERE \"ID\" = 7;",
    )
    add_p(
        doc,
        "Издатель вернул «Цифровой вуз, пленарное», подписчик — «Цифровой вуз, секция». "
        "На рисунке 3 оба текста видны в одной выборке. Названия до разрешения сведены в таблице 3.",
    )
    add_figure(doc, FIG / "conflict.png", "Рисунок 3 — Конференция 7 до разрешения конфликта")
    add_caption(doc, "Таблица 3 — Конференция 7 до разрешения")
    add_table(
        doc,
        ["Сторона", "ID", "Название"],
        [
            ["издатель", "7", "Цифровой вуз, пленарное"],
            ["подписчик", "7", "Цифровой вуз, секция"],
        ],
        [4.5, 2, 10],
    )
    add_p(
        doc,
        "Сверка читает оба названия. Если они различаются, сервер поднимает исключение и называет оба значения. "
        "Пока тексты разные, оператор сверки не выполняется.",
    )
    add_code(
        doc,
        "CREATE OR REPLACE FUNCTION office.check_conflict()\n"
        "RETURNS void\n"
        "LANGUAGE plpgsql\n"
        "AS $$\n"
        "DECLARE\n"
        "  a text;\n"
        "  b text;\n"
        "BEGIN\n"
        "  SELECT \"Название\" INTO a FROM office.\"Конференция\" WHERE \"ID\" = 7;\n"
        "  SELECT \"Название\" INTO b FROM node4.\"Конференция\" WHERE \"ID\" = 7;\n"
        "  IF a IS DISTINCT FROM b THEN\n"
        "    RAISE EXCEPTION 'конфликт репликации: центр [%], узел [%]', a, b;\n"
        "  END IF;\n"
        "END;\n"
        "$$;\n"
        "\n"
        "SELECT office.check_conflict();",
    )
    add_p(doc, "Ответ сервера на рисунке 4:")
    add_code(
        doc,
        "ERROR:  конфликт репликации: центр [Цифровой вуз, пленарное], узел [Цифровой вуз, секция]\n"
        "КОНТЕКСТ:  PL/pgSQL function office.check_conflict() line 9 at RAISE",
    )
    add_figure(doc, FIG / "error.png", "Рисунок 4 — Отказ сверки при двух названиях")

    add_h(doc, "3.4 Устранение конфликта")
    add_p(
        doc,
        "Разрешение оставляет значение издателя. Название подписчика заменяется выборкой из центра по той же конференции. "
        "Своё значение узла при этом отбрасывается.",
    )
    add_code(
        doc,
        "UPDATE node4.\"Конференция\"\n"
        "SET \"Название\" = (\n"
        "  SELECT \"Название\" FROM office.\"Конференция\" WHERE \"ID\" = 7\n"
        ")\n"
        "WHERE \"ID\" = 7;\n"
        "\n"
        "SELECT office.check_conflict();",
    )
    add_p(
        doc,
        "Повторная сверка прошла без ошибки: функция вернула пустой результат. "
        "Контрольная выборка читает строку ещё раз с обеих сторон.",
    )
    add_code(
        doc,
        "SELECT 'центр' AS сторона, \"Название\"\n"
        "FROM office.\"Конференция\" WHERE \"ID\" = 7\n"
        "UNION ALL\n"
        "SELECT 'узел_4', \"Название\"\n"
        "FROM node4.\"Конференция\" WHERE \"ID\" = 7;",
    )
    add_p(
        doc,
        "Обе стороны вернули «Цифровой вуз, пленарное». На рисунке 5 это одна и та же строка. "
        "Содержимое после устранения приведено в таблице 4.",
    )
    add_figure(doc, FIG / "fixed.png", "Рисунок 5 — Конференция 7 после выравнивания")
    add_caption(doc, "Таблица 4 — Конференция 7 после устранения конфликта")
    add_table(
        doc,
        ["Сторона", "ID", "Название"],
        [
            ["издатель", "7", "Цифровой вуз, пленарное"],
            ["подписчик", "7", "Цифровой вуз, пленарное"],
        ],
        [4.5, 2, 10],
    )

    add_h(doc, "4 Выводы", page_break=True)
    add_p(
        doc,
        "Репликация слиянием собрана из издателя office, подписчика node4 и двух статей. "
        "Фрагмент студентов ограничен факультетом 4: после двух вставок в центре лежат Иванов Иван и Сидорова Анна, "
        "на узле остаётся только Сидорова Анна. Иванов Иван, факультет 1, на узел не попал.",
    )
    add_p(
        doc,
        "Конфликт смоделирован на конференции 7. Сначала обе стороны содержали «Цифровой вуз». "
        "Затем центр записал «Цифровой вуз, пленарное», а узел — «Цифровой вуз, секция». "
        "Сверка объявила конфликт текстом «конфликт репликации: центр [Цифровой вуз, пленарное], узел [Цифровой вуз, секция]» "
        "и оператор не выполнила. После записи значения издателя на узел повторная сверка прошла без ошибки, "
        "обе стороны вернули «Цифровой вуз, пленарное».",
    )
    doc.save(OUT)


def main():
    build({title: "…" for title in TOC})
    pages = measure_pages(OUT, TOC)
    build(pages)
    print(pages)


if __name__ == "__main__":
    main()
